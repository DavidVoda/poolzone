type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (cs: string) => string }
const LangContext = createContext<Ctx | null>(null)

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useLocalStorage<Lang>("lang", "cs")
  const t = (cs: string) => (lang === "en" ? (EN[cs] ?? cs) : cs)
  return <LangContext.Provider value={{ lang, setLang, t }}>{children}</LangContext.Provider>
}

export function useT() {
  const ctx = useContext(LangContext)
  if (!ctx) throw new Error("useT must be used within <LangProvider>")
  return ctx
}
